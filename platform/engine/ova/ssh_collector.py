"""Remote inventory collection over SSH for OfflineVA.

Designed for authorized vulnerability assessment only.
Runs only the fixed, read-only collector script generated by collector_commands.
Supports password, private key, jump/bastion host, and legacy algorithms so
older OpenSSH / dropbear servers still work.
"""

from __future__ import annotations

import os
import re
import socket
import subprocess
import tempfile
import threading
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Iterable, Optional

from .collector_commands import collector_command

# Optional paramiko — preferred when present; system ssh is the fallback.
try:
    import paramiko
    from paramiko import SSHClient, AutoAddPolicy, RejectPolicy, WarningPolicy
    from paramiko.ssh_exception import (
        AuthenticationException,
        BadHostKeyException,
        NoValidConnectionsError,
        SSHException,
    )

    HAS_PARAMIKO = True
except ImportError:  # pragma: no cover
    HAS_PARAMIKO = False
    paramiko = None  # type: ignore


LogFn = Callable[[str], None]
ProgressFn = Callable[[str, str, float], None]  # host, status, fraction 0..1


@dataclass
class Target:
    host: str
    port: int = 22
    username: str = "root"
    password: Optional[str] = None
    private_key_path: Optional[str] = None
    private_key_passphrase: Optional[str] = None
    os_family: str = "auto"
    label: str = ""  # optional friendly name for output file

    def display_name(self) -> str:
        return self.label.strip() or self.host


@dataclass
class JumpHost:
    host: str
    port: int = 22
    username: str = "root"
    password: Optional[str] = None
    private_key_path: Optional[str] = None
    private_key_passphrase: Optional[str] = None


@dataclass
class SSHOptions:
    """Connection policy. Defaults favour compatibility with older servers."""

    timeout: float = 30.0
    banner_timeout: float = 30.0
    auth_timeout: float = 30.0
    command_timeout: float = 300.0  # remote collector can be slow on huge hosts
    host_key_policy: str = "warn"  # reject | warn | auto_add
    prefer_paramiko: bool = True
    allow_legacy: bool = True  # enable weak kex / hostkey / cipher for old boxes
    strict_host_key: bool = False
    known_hosts_path: Optional[str] = None
    identity_file_extra: list[str] = field(default_factory=list)


@dataclass
class CollectResult:
    target: Target
    success: bool
    output_path: Optional[Path] = None
    error: str = ""
    elapsed_sec: float = 0.0
    bytes_written: int = 0


# ---------------------------------------------------------------------------
# Legacy algorithm lists (paramiko / OpenSSH)
# ---------------------------------------------------------------------------

# Algorithms that older RHEL 5/6, CentOS 5, Solaris, network appliances still need.
LEGACY_KEX = (
    "diffie-hellman-group-exchange-sha1",
    "diffie-hellman-group14-sha1",
    "diffie-hellman-group1-sha1",
)
LEGACY_HOSTKEYS = (
    "ssh-rsa",
    "ssh-dss",
)
LEGACY_CIPHERS = (
    "aes128-cbc",
    "aes192-cbc",
    "aes256-cbc",
    "3des-cbc",
    "blowfish-cbc",
)
LEGACY_MACS = (
    "hmac-sha1",
    "hmac-md5",
)


def _safe_filename(name: str) -> str:
    cleaned = re.sub(r"[^\w.\-]+", "_", name.strip())[:80]
    return cleaned or "host"


def _ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


# ---------------------------------------------------------------------------
# Paramiko backend
# ---------------------------------------------------------------------------

def _paramiko_policy(policy: str):
    if policy == "reject":
        return RejectPolicy()
    if policy == "auto_add":
        return AutoAddPolicy()
    return WarningPolicy()


def _load_pkey(path: str, passphrase: Optional[str]):
    """Try common private-key formats. Returns None if load fails."""
    if not path or not os.path.isfile(path):
        return None
    loaders = [
        paramiko.RSAKey,
        paramiko.ECDSAKey,
        paramiko.Ed25519Key,
    ]
    # DSSKey still exists on older paramiko
    if hasattr(paramiko, "DSSKey"):
        loaders.append(paramiko.DSSKey)
    last_err = None
    for cls in loaders:
        try:
            return cls.from_private_key_file(path, password=passphrase)
        except Exception as exc:  # noqa: BLE001
            last_err = exc
            continue
    raise SSHException(f"Could not load private key {path}: {last_err}")


def _paramiko_connect(
    host: str,
    port: int,
    username: str,
    password: Optional[str],
    key_path: Optional[str],
    key_pass: Optional[str],
    opts: SSHOptions,
    sock=None,
) -> "SSHClient":
    client = SSHClient()
    if opts.known_hosts_path and os.path.isfile(opts.known_hosts_path):
        client.load_host_keys(opts.known_hosts_path)
    client.set_missing_host_key_policy(_paramiko_policy(opts.host_key_policy))

    connect_kwargs: dict = {
        "hostname": host,
        "port": port,
        "username": username,
        "timeout": opts.timeout,
        "banner_timeout": opts.banner_timeout,
        "auth_timeout": opts.auth_timeout,
        "allow_agent": True,
        "look_for_keys": True,
        "compress": True,
    }
    if sock is not None:
        connect_kwargs["sock"] = sock
    if password:
        connect_kwargs["password"] = password
    if key_path:
        pkey = _load_pkey(key_path, key_pass)
        if pkey is not None:
            connect_kwargs["pkey"] = pkey
            connect_kwargs["look_for_keys"] = False

    if opts.allow_legacy:
        # Re-enable algorithms that modern OpenSSH disables by default.
        disabled = {
            "keys": [],
            "pubkeys": [],
            "kex": [],
            "ciphers": [],
            "macs": [],
        }
        # Empty list means "do not disable" — paramiko interprets this as allow.
        # For true legacy we pass the weak ones explicitly via transport later.
        connect_kwargs["disabled_algorithms"] = disabled

    client.connect(**connect_kwargs)

    if opts.allow_legacy and client.get_transport() is not None:
        # Nudge preferred lists so negotiation can still pick weak options
        # when the server only speaks them.
        transport = client.get_transport()
        try:
            # Prefer modern first, then legacy, so new servers stay secure.
            if hasattr(transport, "_preferred_kex"):
                modern = list(getattr(transport, "_preferred_kex", ()) or ())
                for k in LEGACY_KEX:
                    if k not in modern:
                        modern.append(k)
                transport._preferred_kex = tuple(modern)
            if hasattr(transport, "_preferred_keys"):
                modern = list(getattr(transport, "_preferred_keys", ()) or ())
                for k in LEGACY_HOSTKEYS:
                    if k not in modern:
                        modern.append(k)
                transport._preferred_keys = tuple(modern)
        except Exception:  # pragma: no cover
            pass

    return client


def _run_via_paramiko(
    target: Target,
    script: str,
    opts: SSHOptions,
    jump: Optional[JumpHost],
    log: LogFn,
) -> str:
    """Execute the collector script remotely; return stdout text."""
    jump_client = None
    client = None
    try:
        sock = None
        if jump is not None:
            log(f"[{target.host}] connecting via jump {jump.host}:{jump.port} ...")
            jump_client = _paramiko_connect(
                jump.host,
                jump.port,
                jump.username,
                jump.password,
                jump.private_key_path,
                jump.private_key_passphrase,
                opts,
            )
            transport = jump_client.get_transport()
            if transport is None:
                raise SSHException("Jump host transport unavailable")
            dest_addr = (target.host, target.port)
            local_addr = ("127.0.0.1", 0)
            channel = transport.open_channel("direct-tcpip", dest_addr, local_addr)
            sock = channel
            log(f"[{target.host}] jump channel open")

        log(f"[{target.host}] SSH connect {target.username}@{target.host}:{target.port}")
        client = _paramiko_connect(
            target.host,
            target.port,
            target.username,
            target.password,
            target.private_key_path,
            target.private_key_passphrase,
            opts,
            sock=sock,
        )
        log(f"[{target.host}] authenticated")

        # Feed the script on stdin so nothing is written to the remote disk.
        # Use a plain POSIX sh that exists on virtually every Unix.
        stdin, stdout, stderr = client.exec_command(
            "sh -s",
            timeout=opts.command_timeout,
            get_pty=False,
        )
        stdin.write(script)
        if not script.endswith("\n"):
            stdin.write("\n")
        stdin.channel.shutdown_write()

        # Read with overall deadline
        deadline = time.monotonic() + opts.command_timeout
        out_chunks: list[bytes] = []
        err_chunks: list[bytes] = []
        stdout.channel.settimeout(5.0)
        stderr.channel.settimeout(5.0)

        while True:
            if time.monotonic() > deadline:
                raise TimeoutError(
                    f"Remote collector exceeded {opts.command_timeout:.0f}s"
                )
            if stdout.channel.recv_ready():
                out_chunks.append(stdout.channel.recv(65536))
            if stderr.channel.recv_stderr_ready():
                err_chunks.append(stderr.channel.recv_stderr(65536))
            if stdout.channel.exit_status_ready():
                # Drain remaining
                while stdout.channel.recv_ready():
                    out_chunks.append(stdout.channel.recv(65536))
                while stderr.channel.recv_stderr_ready():
                    err_chunks.append(stderr.channel.recv_stderr(65536))
                break
            time.sleep(0.05)

        exit_status = stdout.channel.recv_exit_status()
        out_text = b"".join(out_chunks).decode("utf-8", errors="replace")
        err_text = b"".join(err_chunks).decode("utf-8", errors="replace").strip()

        if err_text:
            log(f"[{target.host}] remote stderr: {err_text[:500]}")
        if exit_status != 0 and "VA_OFFLINE_INVENTORY_BEGIN" not in out_text:
            raise SSHException(
                f"Remote shell exited {exit_status}"
                + (f": {err_text[:300]}" if err_text else "")
            )
        if "VA_OFFLINE_INVENTORY_BEGIN" not in out_text:
            raise SSHException(
                "Collector markers missing — remote shell may have rejected the script "
                "or the account has no read access to package databases."
            )
        return out_text
    finally:
        if client is not None:
            try:
                client.close()
            except Exception:
                pass
        if jump_client is not None:
            try:
                jump_client.close()
            except Exception:
                pass


# ---------------------------------------------------------------------------
# System OpenSSH backend (better for very old servers when ssh is available)
# ---------------------------------------------------------------------------

def _build_ssh_base_args(opts: SSHOptions) -> list[str]:
    args = [
        "ssh",
        "-o", "BatchMode=no",
        "-o", "StrictHostKeyChecking=accept-new" if not opts.strict_host_key else "StrictHostKeyChecking=yes",
        "-o", f"ConnectTimeout={int(opts.timeout)}",
        "-o", "ServerAliveInterval=15",
        "-o", "ServerAliveCountMax=4",
        "-o", "LogLevel=ERROR",
    ]
    if opts.allow_legacy:
        # Force acceptance of legacy algorithms when the local OpenSSH still has them.
        args += [
            "-o", "HostKeyAlgorithms=+ssh-rsa,ssh-dss",
            "-o", "PubkeyAcceptedAlgorithms=+ssh-rsa,ssh-dss",
            "-o", "KexAlgorithms=+diffie-hellman-group14-sha1,diffie-hellman-group1-sha1,diffie-hellman-group-exchange-sha1",
            "-o", "Ciphers=+aes128-cbc,aes192-cbc,aes256-cbc,3des-cbc",
            "-o", "MACs=+hmac-sha1,hmac-md5",
        ]
    if opts.known_hosts_path:
        args += ["-o", f"UserKnownHostsFile={opts.known_hosts_path}"]
    for ident in opts.identity_file_extra:
        if ident:
            args += ["-i", ident]
    return args


def _run_via_system_ssh(
    target: Target,
    script: str,
    opts: SSHOptions,
    jump: Optional[JumpHost],
    log: LogFn,
) -> str:
    """Use the local OpenSSH client. Password auth needs sshpass when available."""
    base = _build_ssh_base_args(opts)

    if target.private_key_path:
        base += ["-i", target.private_key_path]
        # Prefer key-only when a key is given
        base += ["-o", "PreferredAuthentications=publickey"]
    elif target.password:
        base += ["-o", "PreferredAuthentications=password,keyboard-interactive"]

    if jump is not None:
        jump_parts = [f"-p {jump.port}"]
        if jump.private_key_path:
            jump_parts.append(f"-i {jump.private_key_path}")
        jump_cmd = (
            f"ssh {' '.join(jump_parts)} "
            f"-o StrictHostKeyChecking=accept-new "
            f"{jump.username}@{jump.host}"
        )
        base += ["-J", f"{jump.username}@{jump.host}:{jump.port}"]
        # -J is cleaner on modern OpenSSH; ProxyCommand is the fallback for old clients
        # but we keep -J as primary.

    dest = f"{target.username}@{target.host}"
    cmd = base + ["-p", str(target.port), dest, "sh -s"]

    env = os.environ.copy()
    # sshpass for non-interactive password (common on Windows WSL / Linux analyst boxes)
    use_sshpass = False
    if target.password and not target.private_key_path:
        if _which("sshpass"):
            use_sshpass = True
            cmd = ["sshpass", "-e"] + cmd
            env["SSHPASS"] = target.password
        else:
            raise RuntimeError(
                "Password auth via system ssh requires 'sshpass' on PATH, "
                "or install paramiko (preferred). Provide a private key instead."
            )

    log(f"[{target.host}] system-ssh: {' '.join(c for c in cmd if c != target.password)}")
    proc = subprocess.Popen(
        cmd,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=env,
    )
    try:
        stdout_b, stderr_b = proc.communicate(
            input=script.encode("utf-8"),
            timeout=opts.command_timeout,
        )
    except subprocess.TimeoutExpired:
        proc.kill()
        raise TimeoutError(f"Remote collector exceeded {opts.command_timeout:.0f}s")

    out_text = (stdout_b or b"").decode("utf-8", errors="replace")
    err_text = (stderr_b or b"").decode("utf-8", errors="replace").strip()
    if err_text:
        log(f"[{target.host}] remote stderr: {err_text[:500]}")
    if proc.returncode != 0 and "VA_OFFLINE_INVENTORY_BEGIN" not in out_text:
        raise RuntimeError(
            f"ssh exited {proc.returncode}"
            + (f": {err_text[:300]}" if err_text else "")
        )
    if "VA_OFFLINE_INVENTORY_BEGIN" not in out_text:
        raise RuntimeError("Collector markers missing in remote output")
    return out_text


def _which(name: str) -> Optional[str]:
    from shutil import which
    return which(name)


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def collect_one(
    target: Target,
    output_dir: Path,
    opts: Optional[SSHOptions] = None,
    jump: Optional[JumpHost] = None,
    log: Optional[LogFn] = None,
) -> CollectResult:
    """Connect to one host, run the safe collector, write a TXT inventory file."""
    opts = opts or SSHOptions()
    log = log or (lambda _m: None)
    t0 = time.monotonic()
    output_dir = Path(output_dir)
    _ensure_dir(output_dir)

    try:
        script = collector_command(target.os_family)
    except ValueError as exc:
        return CollectResult(target=target, success=False, error=str(exc))

    backend = "paramiko" if (opts.prefer_paramiko and HAS_PARAMIKO) else "system-ssh"
    if backend == "paramiko" and not HAS_PARAMIKO:
        backend = "system-ssh"
    if backend == "system-ssh" and not _which("ssh"):
        return CollectResult(
            target=target,
            success=False,
            error="Neither paramiko nor system 'ssh' is available. Install paramiko or OpenSSH client.",
        )

    log(f"[{target.host}] backend={backend} family={target.os_family}")

    try:
        if backend == "paramiko":
            text = _run_via_paramiko(target, script, opts, jump, log)
        else:
            text = _run_via_system_ssh(target, script, opts, jump, log)
    except AuthenticationException as exc:
        return CollectResult(
            target=target,
            success=False,
            error=f"Authentication failed: {exc}",
            elapsed_sec=time.monotonic() - t0,
        )
    except (BadHostKeyException, NoValidConnectionsError, SSHException, OSError, RuntimeError, TimeoutError) as exc:
        return CollectResult(
            target=target,
            success=False,
            error=str(exc),
            elapsed_sec=time.monotonic() - t0,
        )
    except Exception as exc:  # noqa: BLE001
        return CollectResult(
            target=target,
            success=False,
            error=f"Unexpected error: {type(exc).__name__}: {exc}",
            elapsed_sec=time.monotonic() - t0,
        )

    # Derive a stable filename
    stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    fname = f"inventory_{_safe_filename(target.display_name())}_{stamp}.txt"
    out_path = output_dir / fname
    # Avoid overwrite if two hosts share a label in the same second
    if out_path.exists():
        out_path = output_dir / f"inventory_{_safe_filename(target.display_name())}_{stamp}_{os.getpid()}.txt"

    try:
        out_path.write_text(text, encoding="utf-8", newline="\n")
    except OSError as exc:
        return CollectResult(
            target=target,
            success=False,
            error=f"Failed to write {out_path}: {exc}",
            elapsed_sec=time.monotonic() - t0,
        )

    log(f"[{target.host}] saved {out_path} ({len(text)} bytes)")
    return CollectResult(
        target=target,
        success=True,
        output_path=out_path,
        elapsed_sec=time.monotonic() - t0,
        bytes_written=len(text.encode("utf-8")),
    )


def collect_many(
    targets: Iterable[Target],
    output_dir: Path,
    opts: Optional[SSHOptions] = None,
    jump: Optional[JumpHost] = None,
    log: Optional[LogFn] = None,
    progress: Optional[ProgressFn] = None,
    stop_event: Optional[threading.Event] = None,
    max_workers: int = 1,
) -> list[CollectResult]:
    """Collect from multiple targets sequentially (default) or lightly parallel.

    max_workers > 1 runs a simple thread pool. Keep low for jump-host / rate limits.
    """
    opts = opts or SSHOptions()
    log = log or (lambda _m: None)
    progress = progress or (lambda *_a: None)
    stop_event = stop_event or threading.Event()
    targets = list(targets)
    total = len(targets)
    results: list[CollectResult] = []

    if total == 0:
        return results

    if max_workers <= 1:
        for i, t in enumerate(targets):
            if stop_event.is_set():
                log("Collection stopped by user")
                break
            progress(t.host, "running", i / total)
            r = collect_one(t, output_dir, opts=opts, jump=jump, log=log)
            results.append(r)
            status = "ok" if r.success else f"fail: {r.error[:80]}"
            progress(t.host, status, (i + 1) / total)
            log(f"[{t.host}] done success={r.success} ({r.elapsed_sec:.1f}s)")
        return results

    # Simple thread pool with bounded concurrency
    from concurrent.futures import ThreadPoolExecutor, as_completed

    lock = threading.Lock()
    done_count = 0

    def _job(t: Target) -> CollectResult:
        nonlocal done_count
        if stop_event.is_set():
            return CollectResult(target=t, success=False, error="Cancelled")
        progress(t.host, "running", done_count / total)
        r = collect_one(t, output_dir, opts=opts, jump=jump, log=log)
        with lock:
            done_count += 1
            progress(t.host, "ok" if r.success else "fail", done_count / total)
        return r

    with ThreadPoolExecutor(max_workers=max_workers) as pool:
        futs = {pool.submit(_job, t): t for t in targets}
        for fut in as_completed(futs):
            if stop_event.is_set():
                break
            try:
                results.append(fut.result())
            except Exception as exc:  # noqa: BLE001
                t = futs[fut]
                results.append(
                    CollectResult(target=t, success=False, error=str(exc))
                )
    return results


def parse_target_list(text: str, default_user: str = "root", default_port: int = 22, default_family: str = "auto") -> list[Target]:
    """Parse a multi-line target list.

    Accepted lines (blank / # comments ignored):
        host
        host:port
        user@host
        user@host:port
        user@host:port,os_family
        user@host:port,os_family,label
    """
    targets: list[Target] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        family = default_family
        label = ""
        parts = [p.strip() for p in line.split(",")]
        left = parts[0]
        if len(parts) >= 2 and parts[1]:
            family = parts[1]
        if len(parts) >= 3 and parts[2]:
            label = parts[2]

        user = default_user
        hostport = left
        if "@" in left:
            user, hostport = left.rsplit("@", 1)
        port = default_port
        host = hostport
        if ":" in hostport:
            # IPv6 in [brackets]:port or plain host:port
            if hostport.startswith("[") and "]:" in hostport:
                host, port_s = hostport[1:].split("]:", 1)
                port = int(port_s)
            else:
                host, port_s = hostport.rsplit(":", 1)
                if port_s.isdigit():
                    port = int(port_s)
                else:
                    host = hostport
        targets.append(
            Target(
                host=host.strip(),
                port=port,
                username=user.strip() or default_user,
                os_family=family or default_family,
                label=label,
            )
        )
    return targets


def export_collector_bash(family: str, path: Path) -> Path:
    """Write the safe collector script to a .sh file (LF endings)."""
    path = Path(path)
    text = collector_command(family)
    path.write_text(text, encoding="utf-8", newline="\n")
    try:
        path.chmod(0o755)
    except OSError:
        pass
    return path
